export function getModuleChatFAQs(moduleId: string): string[] | null {
  const faqs = MODULE_CHAT_FAQS[moduleId];
  if (!faqs || faqs.length === 0) return null;
  return faqs;
}

/**
 * Generic fallback for modules not yet in the curated registry above.
 * Generates two title-anchored questions so every module surfaces
 * something relevant even before curation lands.
 */
export function getDefaultFAQsForTitle(title: string): string[] {
  return [
    `מה הכי חשוב לדעת על ${title}?`,
    `איך ${title} משפיע על הכסף שלי?`,
  ];
}
