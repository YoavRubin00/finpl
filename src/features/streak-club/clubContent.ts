const DROPS_BY_TABLE: Record<TableId, ClubDrop[]> = {
  stocks: STOCKS_DROPS,
  realestate: REALESTATE_DROPS,
  savings: SAVINGS_DROPS,
};

/** ימים-מאז-אפוך מ-dateKey ("YYYY-MM-DD", יום-ישראלי) — בסיס לרוטציה דטרמיניסטית */
function dayIndex(dateKey: string): number {
  const t = Date.parse(`${dateKey}T00:00:00Z`);
  return Number.isFinite(t) ? Math.floor(t / 86_400_000) : 0;
}

/** אופסט קבוע פר-שולחן כדי שהשולחנות לא "יתחלפו יחד" באותו מקצב */
const TABLE_PHASE: Record<TableId, number> = { stocks: 0, realestate: 3, savings: 5 };

/** הדרופ של שולחן ביום נתון — דטרמיניסטי, מתחלף כל יום-ישראלי */
export function getDropForDate(table: TableId, dateKey: string): ClubDrop {
  const drops = DROPS_BY_TABLE[table];
  const idx = (dayIndex(dateKey) + TABLE_PHASE[table]) % drops.length;
  return drops[idx];
}

/** הטיזר של מחר (לפינאלת "סגרת את הטרקלין") — מחושב, לא מתוחזק ידנית */
export function getTomorrowTease(table: TableId, dateKey: string): string {
  const drops = DROPS_BY_TABLE[table];
  const idx = (dayIndex(dateKey) + 1 + TABLE_PHASE[table]) % drops.length;
  return drops[idx].teaseHe;
}
