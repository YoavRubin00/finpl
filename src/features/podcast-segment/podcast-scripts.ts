/**
 * Returns the final PodcastSegment list (with audio.uri filled in)
 * to be imported by individual chapter data files.
 */
export const buildPodcasts = (
  urlMap: Readonly<Record<string, string>>,
): PodcastSegment[] =>
  PODCAST_DRAFTS.map((draft) => {
    const uri = urlMap[draft.id];
    if (!uri) {
      throw new Error(`Missing audio URL for podcast: ${draft.id}`);
    }
    const { scriptForTTS: _ttsScript, blobKey: _key, ...rest } = draft;
    return { ...rest, audio: { uri } };
  });
